"""Rasterize the supplied calligraphy and derive a compact, stroke-following reveal."""
from pathlib import Path
import argparse, io, math, subprocess, xml.etree.ElementTree as ET
import numpy as np
from scipy import ndimage
from skimage.morphology import skeletonize
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent
parser = argparse.ArgumentParser()
parser.add_argument('--output', type=Path, default=ROOT/'preview/boot')
args = parser.parse_args()
out = args.output.resolve(); out.mkdir(parents=True, exist_ok=True)
W, H, STEPS = 234, 77, 42

# Accept only local path geometry from the reference SVG; no scripts or links.
source = ET.parse(ROOT/'media/Besmellah.svg').getroot()
svg = ET.Element('svg', xmlns='http://www.w3.org/2000/svg', width='789', height='259', viewBox='0 0 789 259')
for p in source:
    if p.tag.split('}')[-1] != 'path': continue
    attrs = {k:v for k,v in p.attrib.items() if k in {'d','transform','fill-rule'}}
    attrs['fill'] = '#ffffff'
    ET.SubElement(svg, 'path', attrs)
sanitized = out/'calligraphy-white.svg'; ET.ElementTree(svg).write(sanitized, encoding='utf-8')
subprocess.run(['rsvg-convert','-w',str(W*4),'-h',str(H*4),str(sanitized),'-o',str(out/'logo-hi.png')], check=True)
logo = Image.open(out/'logo-hi.png').convert('RGBA').resize((W,H),Image.Resampling.LANCZOS)
alpha = np.array(logo.getchannel('A'))
skel = skeletonize(alpha > 80)
labels, count = ndimage.label(skel, np.ones((3,3)))
components = []
for label in range(1,count+1):
    ys,xs = np.where(labels == label)
    nodes = set(zip(ys.tolist(),xs.tolist()))
    if nodes: components.append(nodes)
components.sort(key=lambda nodes:max(x for y,x in nodes),reverse=True)
ordered = []
neighbors = lambda p,nodes:[(p[0]+dy,p[1]+dx) for dy in (-1,0,1) for dx in (-1,0,1) if (dy or dx) and (p[0]+dy,p[1]+dx) in nodes]
for nodes in components:
    endpoints=[p for p in nodes if len(neighbors(p,nodes))==1]
    start=max(endpoints or list(nodes),key=lambda p:(p[1],-p[0]))
    visited={start};stack=[(start,(0,-1))];ordered.append(start)
    while stack:
        current,direction=stack[-1]
        choices=[p for p in neighbors(current,nodes) if p not in visited]
        if not choices:stack.pop();continue
        def smoothness(p):
            dy,dx=p[0]-current[0],p[1]-current[1]
            return (dy*direction[0]+dx*direction[1])/math.hypot(dy,dx)
        nxt=max(choices,key=smoothness)
        visited.add(nxt);ordered.append(nxt)
        stack.append((nxt,(nxt[0]-current[0],nxt[1]-current[1])))
    assert visited==nodes
times=np.full((H,W),255,dtype=np.uint8)
for i,(y,x) in enumerate(ordered):times[y,x]=min(STEPS-1,int(i*STEPS/len(ordered)))
_,nearest=ndimage.distance_transform_edt(~skel,return_indices=True)
reveal=times[nearest[0],nearest[1]].copy()
reveal[alpha==0]=255
assert len(ordered)>100 and np.max(reveal[alpha>0])<STEPS

def robot(pose):
    bounce=[0,-1,0,1][pose]
    # Original minimal happy robot; rounded head, smiling eyes, raised hands, feet.
    eye_left='M15 14 Q18 9 21 14' if pose!=2 else 'M15 13 L21 13'
    eye_right='M29 14 Q32 9 35 14' if pose!=2 else 'M29 13 L35 13'
    mouth='M21 21 Q25 27 29 21' if pose in (1,3) else 'M21 21 Q25 25 29 21'
    arm='M43 30 L47 26' if pose==1 else 'M43 30 L47 29'
    doc=f'''<svg xmlns="http://www.w3.org/2000/svg" width="50" height="44" viewBox="0 0 50 44">
    <g stroke="white" fill="none" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" transform="translate(0,{bounce})">
      <rect x="6" y="3" width="38" height="28" rx="10"/>
      <path d="{eye_left} {eye_right} {mouth}"/>
      <path d="M7 30 L3 27 {arm} M18 33 Q25 36 32 33 M18 35 L18 39 M32 35 L32 39 M14 40 L21 40 M29 40 L36 40"/>
    </g></svg>'''
    r=subprocess.run(['rsvg-convert','-w','200','-h','176'],input=doc.encode(),capture_output=True,check=True)
    return Image.open(io.BytesIO(r.stdout)).convert('RGBA').resize((50,44),Image.Resampling.LANCZOS).getchannel('A')
faces=[robot(i) for i in range(4)]

def array(name, values):
    b=bytes(values)
    return f'const uint8_t {name}[] PROGMEM = {{\n'+''.join('  '+','.join(f'{x:3}' for x in b[i:i+32])+',\n' for i in range(0,len(b),32))+'};\n'
header='''// Generated by make_boot_assets.py from the supplied Besmellah.svg.
#pragma once
#include <Arduino.h>
constexpr uint16_t BOOT_LOGO_WIDTH = 234;
constexpr uint16_t BOOT_LOGO_HEIGHT = 77;
constexpr uint8_t BOOT_WRITE_STEPS = 42;
constexpr uint8_t BOOT_FACE_WIDTH = 50;
constexpr uint8_t BOOT_FACE_HEIGHT = 44;
'''
header+=array('bootLogoAlpha',alpha.flatten())+array('bootLogoReveal',reveal.flatten())
header+=array('bootFaceAlpha',b''.join(face.tobytes() for face in faces))
(ROOT/'ats-mini/BootScreenAssets.h').write_text(header)
logo.save(out/'besmellah-white.png')

try:font=ImageFont.truetype('/System/Library/Fonts/Supplemental/Arial.ttf',12)
except OSError:font=ImageFont.load_default()
frames=out/'frames';frames.mkdir(exist_ok=True)
for old in frames.glob('*.png'):old.unlink()
for frame in range(STEPS+16):
    age=frame-reveal.astype(np.int16)
    shown=(alpha.astype(float)*np.clip((age+1)/3,0,1)).astype(np.uint8)
    shown[reveal==255]=0
    im=Image.new('RGB',(320,170))
    white=Image.new('RGB',(W,H),'white');im.paste(white,(43,2),Image.fromarray(shown))
    face=faces[(frame//6)%4] if frame<STEPS+2 else faces[0]
    im.paste(Image.new('RGB',(50,44),'white'),(135,85),face)
    draw=ImageDraw.Draw(im)
    text='Checking antenna...';box=draw.textbbox((0,0),text,font=font)
    draw.text(((320-(box[2]-box[0]))/2,138),text,font=font,fill='white')
    if frame>=STEPS+2:
        draw.line((30,162,30+int((frame-STEPS-2)/13*100),162),fill=(255,165,0),width=3)
    im.save(frames/f'{frame:03d}.png')
im.save(out/'boot-screen-preview.png')
subprocess.run(['ffmpeg','-hide_banner','-loglevel','error','-y','-framerate','25','-i',str(frames/'%03d.png'),'-an','-c:v','libx264','-crf','16','-pix_fmt','yuv420p','-movflags','+faststart',str(out/'boot-screen-preview.mp4')],check=True)
print(f'Generated {len(ordered)} skeleton points in {len(components)} components; embedded bytes={W*H*2+50*44*4}')
